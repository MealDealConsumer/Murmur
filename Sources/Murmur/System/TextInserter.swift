import AppKit
import Carbon.HIToolbox

struct InsertOutcome {
    enum Kind { case pasted, notPasted }
    var kind: Kind
    var focus: FocusInfo
    var inserted: String
    var token = 0
}

enum TextInserter {
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")

    struct Snapshot {
        var items: [[NSPasteboard.PasteboardType: Data]]
    }

    static func snapshot() -> Snapshot {
        let pb = NSPasteboard.general
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        for item in pb.pasteboardItems ?? [] {
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            if !dict.isEmpty { items.append(dict) }
        }
        return Snapshot(items: items)
    }

    static func restore(_ snap: Snapshot) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let items: [NSPasteboardItem] = snap.items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    // Marks the text so clipboard managers skip it when it is only passing through
    private static func write(_ text: String, passingThrough: Bool) -> Int {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        if passingThrough {
            pb.setData(Data(), forType: transient)
            pb.setData(Data(), forType: autoGenerated)
        }
        pb.setString(Bundle.main.bundleIdentifier ?? "Murmur", forType: source)
        return pb.changeCount
    }

    // The clipboard from before the first of several quick pastes is the one worth putting back
    private static var pending: (snapshot: Snapshot, token: Int, count: Int)?
    private static var token = 0

    static func copy(_ text: String) {
        pending = nil
        _ = write(text, passingThrough: false)
    }

    // Tests that must never type into whatever app is in front turn the keystroke off and count any attempt
    static var blockPaste = false
    private(set) static var blockedPastes = 0

    /* The clipboard only carries the text for the moment the paste needs it and always gets the old contents back.
    Nothing is ever left on it, so whatever was copied before dictating is still there to paste afterwards. */
    static func insert(_ text: String, completion: @escaping (InsertOutcome) -> Void) {
        // A blocked test never reads the real front app so its result does not depend on what I have open
        let focus = blockPaste ? FocusInfo() : FocusInfo.current()
        Log.info("insert into \(focus.bundleId) role=\(focus.role) editable=\(focus.editable)")

        if focus.editable == .no {
            completion(InsertOutcome(kind: .notPasted, focus: focus, inserted: text))
            return
        }
        var payload = text
        if let spacing = focus.spacing(for: text) {
            if spacing.leading { payload = " " + payload }
            if spacing.trailing { payload += " " }
        } else {
            // Without a readable caret a trailing space keeps back to back dictations apart
            payload += " "
        }
        let snap = pending?.snapshot ?? snapshot()
        let count = write(payload, passingThrough: true)
        token += 1
        let mine = token
        pending = (snap, mine, count)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            if blockPaste { blockedPastes += 1 } else { postCommandV() }
            completion(InsertOutcome(kind: .pasted, focus: focus, inserted: payload, token: mine))
            DispatchQueue.main.asyncAfter(deadline: .now() + 2.0) { putBack(mine) }
        }
    }

    // Once the text shows up in the field the app has read the clipboard so it can go back straight away
    static func pasteLanded(_ mine: Int) {
        putBack(mine)
    }

    private static func putBack(_ mine: Int) {
        guard let p = pending, p.token == mine else { return }
        pending = nil
        // Something copied in the meantime is newer than what I saved so it stays
        if NSPasteboard.general.changeCount == p.count { restore(p.snapshot) }
    }

    private static func postCommandV() {
        let src = CGEventSource(stateID: .privateState)
        let cmd = CGKeyCode(kVK_Command)
        let v = CGKeyCode(kVK_ANSI_V)
        let events = [
            CGEvent(keyboardEventSource: src, virtualKey: cmd, keyDown: true),
            CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true),
            CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false),
            CGEvent(keyboardEventSource: src, virtualKey: cmd, keyDown: false),
        ]
        for (i, e) in events.enumerated() {
            e?.flags = i == 3 ? [] : .maskCommand
            e?.post(tap: .cghidEventTap)
            usleep(8000)
        }
    }
}
